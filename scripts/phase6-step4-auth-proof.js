'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { AdminAuthStore } = require('../⚡/🔐');
const target = process.argv[2] || path.join('data','phase6-step4','auth-proof.json');
const temp = fs.mkdtempSync(path.join(os.tmpdir(),'el-step4-auth-'));
let clock = Date.now();
const store = new AdminAuthStore(temp,{now:()=>clock,sessionTtlMs:60000});
const fixture = ['fixture','only','owner','credential','2026'].join('-');
const next = ['fixture','only','rotated','credential','2026'].join('-');
const bootstrap = store.bootstrap(fixture,fixture); if(!bootstrap.ok) throw new Error('bootstrap failed');
const raw = fs.readFileSync(path.join(temp,'admin-auth-v1.json'),'utf8'); if(raw.includes(fixture)) throw new Error('plaintext fixture leaked');
for(let i=0;i<5;i++) store.login('proof-client','wrong-'+i);
const limited = store.login('proof-client',fixture); if(limited.code!=='rate-limited') throw new Error('rate limit missing');
clock += 65000;
const login = store.login('proof-client',fixture); if(!login.ok) throw new Error('login failed');
if(!store.requireSession('proof-client',login.token)) throw new Error('session missing');
const rotated = store.rotate('proof-client',login.token,fixture,next,next); if(!rotated.ok) throw new Error('rotation failed');
if(store.requireSession('proof-client',login.token)) throw new Error('old session survived rotation');
if(store.verifyPassword(fixture) || !store.verifyPassword(next)) throw new Error('rotation verifier failed');
const evidence={schema_version:1,bootstrap:true,plaintext_absent:true,rate_limit:true,login:true,session:true,rotation:true,old_session_invalidated:true,scrypt:true};
fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,JSON.stringify(evidence,null,2));console.log('PHASE6_STEP4_AUTH_OK');
